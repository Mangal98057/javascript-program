const day = 3
switch (day) {
    case 1:
        console.log("monday")
        
        break;
    case 2:
       console.log("thusday") 
        
        break;
    case 3:
        console.log("wedesday")
        
        break;

    default:
        console.log("mistake")
        break;
}

/*
| Keyword   | Meaning                 |
| --------- | ----------------------- |
| `switch`  | Checks multiple values  |
| `case`    | Defines condition       |
| `break`   | Stops execution         |
| `default` | Runs if no case matches |
*/



// The switch statement is used to check multiple possible values of a variable.

// It helps execute different blocks of code based on different conditions.

// switch is an alternative to using many if...else if statements.