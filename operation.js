//1. Arithmetic oprators

// | Operator | Meaning        |
// | -------- | -------------- |
// | `+`      | Addition       |
// | `-`      | Subtraction    |
// | `*`      | Multiplication |
// | `/`      | Division       |
// | `%`      | Modulus        |
// | `**`     | Exponent       |

console.log(2**3) //2*2*2 =8

// 2. Assignment Operators
//Used to assign values.

/*
| Operator | Example  |
| -------- | -------- |
| `=`      | `x = 5`  |
| `+=`     | `x += 2` |
| `-=`     | `x -= 2` |
| `*=`     | `x *= 2` |
| `/=`     | `x /= 2` |


*/

let x = 10;

x += 5;

console.log(x); //15


// 3. Comparison Operators
//Used to compare values.

/*

| Operator | Meaning          |
| -------- | ---------------- |
| `==`     | Equal            |
| `===`    | Strict Equal     |
| `!=`     | Not Equal        |
| `!==`    | Strict Not Equal |
| `>`      | Greater Than     |
| `<`      | Less Than        |
| `>=`     | Greater Equal    |
| `<=`     | Less Equal       |

 */
console.log(5 == "5"); // true

